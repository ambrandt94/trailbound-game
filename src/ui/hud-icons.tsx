export type HudIconName = keyof typeof BITMAPS;

export function HudIcon(props: { name: HudIconName }) {
  const rows = BITMAPS[props.name];
  const rects: Array<{ x: number; y: number }> = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) if (row[x] === '#') rects.push({ x, y });
  });
  return (
    <svg
      class="hud-icon"
      viewBox="0 0 8 8"
      aria-hidden="true"
      focusable="false"
      shape-rendering="crispEdges"
    >
      {rects.map((r) => (
        <rect key={`${r.x},${r.y}`} x={r.x} y={r.y} width="1" height="1" fill="currentColor" />
      ))}
    </svg>
  );
}
